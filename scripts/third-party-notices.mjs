// Generates THIRD_PARTY_NOTICES.md: bundled programs, plus every Rust crate (normal dependencies
// reachable from `rabbit` on the build platform) and npm package (non-dev, from package-lock.json) that ships
// in Rabbit, with its declared license. Usage: node scripts/third-party-notices.mjs
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = process.env.CARGO_BUILD_TARGET ?? execFileSync("rustc", ["-vV"], { encoding: "utf8" }).match(/^host: (.+)$/m)[1];
const linux = target.includes("linux");
const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--filter-platform", target, "--manifest-path", join(root, "src-tauri", "Cargo.toml")], {
    maxBuffer: 256 * 1024 * 1024,
    encoding: "utf8",
  }),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const rootId = meta.resolve.root;
const seen = new Set();
const stack = [rootId];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    // Normal dependencies only (build scripts and dev-dependencies don't ship).
    if (d.dep_kinds.some((k) => k.kind === null)) stack.push(d.pkg);
  }
}
seen.delete(rootId);
const crates = [...seen].map((id) => pkgs.get(id)).sort((a, b) => a.name.localeCompare(b.name));

const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const npm = Object.entries(lock.packages)
  .filter(([path, p]) => path.startsWith("node_modules/") && !p.dev && !p.devOptional)
  .map(([path, p]) => {
    const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
    let license = p.license;
    if (!license) {
      try {
        license = JSON.parse(readFileSync(join(root, path, "package.json"), "utf8")).license;
      } catch {}
    }
    return { name, version: p.version, license: license ?? "see package" };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const count = (list) => {
  const m = new Map();
  for (const x of list) m.set(x.license ?? "unspecified", (m.get(x.license ?? "unspecified") ?? 0) + 1);
  return [...m].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ");
};

const out = `# Third-party notices

Rabbit is MIT-licensed (see LICENSE). It ships the following third-party software, each under its own license.
This file is generated by \`scripts/third-party-notices.mjs\`; the installer copies it, and the license texts
below, into \`<install folder>\\licenses\\\`.

## Bundled programs

| Program | Version | License | Source |
|---|---|---|---|
| yt-dlp | pinned in \`scripts/${linux ? "fetch-sidecars-linux.py" : "fetch-sidecars.ps1"}\` | Unlicense (public domain) — \`licenses/yt-dlp-LICENSE.txt\` | https://github.com/yt-dlp/yt-dlp |
| FFmpeg, FFprobe ${linux ? "(static LGPL build)" : "(+ 7 FFmpeg DLLs)"} | n9.0.2 (BtbN LGPL build, pinned) | LGPL-3.0-or-later — \`${linux ? "tools" : "licenses"}/FFmpeg-LICENSE.txt\` | Build: \`${linux ? "tools" : "licenses"}/FFmpeg-SOURCE.txt\`; source: https://git.ffmpeg.org/ffmpeg.git, build scripts: https://github.com/BtbN/FFmpeg-Builds |
${linux ? "" : "| Microsoft Edge WebView2 bootstrapper | — | Microsoft Software License Terms | Installed by Windows / the bootstrapper |"}

FFmpeg is used as separate programs started by Rabbit (no linking into Rabbit), and the exact build and its source are
identified above, as the LGPL requires. To use a different FFmpeg build, replace the files in the install folder.

## Fonts

IBM Plex Sans and IBM Plex Mono (via \`@fontsource\`) — SIL Open Font License 1.1.

## Rust crates (${crates.length}) — ${count(crates)}

| Crate | Version | License |
|---|---|---|
${crates.map((c) => `| ${c.name} | ${c.version} | ${c.license ?? (c.license_file ? "see crate" : "unspecified")} |`).join("\n")}

## npm packages (${npm.length}) — ${count(npm)}

| Package | Version | License |
|---|---|---|
${npm.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`).join("\n")}
`;
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), out);
console.log(`crates: ${crates.length} — ${count(crates)}`);
console.log(`npm: ${npm.length} — ${count(npm)}`);
const odd = [...crates.map((c) => ({ n: c.name, l: c.license })), ...npm.map((p) => ({ n: p.name, l: p.license }))].filter(
  (x) => !x.l || /GPL|AGPL|SSPL|BUSL|proprietary|unspecified/i.test(x.l) && !/LGPL|OR MIT|OR Apache|MIT OR|Apache-2.0 OR/i.test(x.l),
);
console.log("needs a look:", odd.map((x) => `${x.n}: ${x.l}`).join("; ") || "none");
